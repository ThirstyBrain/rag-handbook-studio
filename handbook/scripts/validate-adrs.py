"""Lint adr/ADR-*.md and (optionally) regenerate docs/09-Architecture-Decision-Records.md.

The rules live in docs/exercises/ch31_adr_lint.py (Chapter 31), where they are unit-tested and mutation-checked.
This script is the CI entry point: it fails (exit 1) on any `error` finding. Warnings and info are printed and
recorded in the catalogue; they are for the decision owners, not for the build.

Usage:  python -I scripts/validate-adrs.py [--write-catalogue]
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "docs" / "exercises" / "ch31_adr_lint.py"
OUT = ROOT / "docs" / "09-Architecture-Decision-Records.md"


def load():
    spec = importlib.util.spec_from_file_location("adr_lint", RULES)
    mod = importlib.util.module_from_spec(spec)
    assert spec and spec.loader
    sys.modules["adr_lint"] = mod
    spec.loader.exec_module(mod)
    return mod


def render(mod, adrs, findings, rows) -> str:
    lines = [
        "# Architecture Decision Records: Catalogue",
        "",
        "> Generated by `python -I scripts/validate-adrs.py --write-catalogue` from `adr/ADR-*.md`. Do not edit by hand: edit the ADRs and regenerate. "
        "The rules that produce the findings below are in `docs/exercises/ch31_adr_lint.py` (Chapter 31). A clean lint means the records are "
        "well-formed and consistent with each other; it does not mean the decisions are right or that the code follows them.",
        "",
        f"Records: {len(adrs)}. Status counts: "
        + ", ".join(f"{s} {sum(1 for r in rows if r['status'] == s)}" for s in sorted({r['status'] for r in rows})) + ".",
        "",
        "| ADR | Title | Status | Date | Amendments | Cited by |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        cited = ", ".join(f"{n:03d}" for n in r["cited_by"]) or "none"
        lines.append(f"| [{r['n']:03d}](../adr/{next(a.filename for a in adrs if a.number == r['n'])}) | {r['title']} | {r['status']} | {r['date']} | {r['amendments']} | {cited} |")
    lines += ["", "## Lint findings", ""]
    for sev in ("error", "warn", "info"):
        fs = [f for f in findings if f.severity == sev]
        lines.append(f"**{sev}: {len(fs)}**")
        lines.append("")
        for f in fs:
            lines.append(f"- `{f.adr}` {f.rule}: {f.message}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    mod = load()
    adrs = mod.real_adrs()
    findings = mod.lint(adrs)
    rows = mod.catalogue(adrs)
    errors = [f for f in findings if f.severity == "error"]
    for f in findings:
        print(f"{f.severity.upper():5s} {f.adr}: {f.rule}: {f.message}")
    print(f"{len(adrs)} ADRs, {len(errors)} errors, {sum(f.severity == 'warn' for f in findings)} warnings, {sum(f.severity == 'info' for f in findings)} info")
    if "--write-catalogue" in sys.argv:
        OUT.write_text(render(mod, adrs, findings, rows), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
